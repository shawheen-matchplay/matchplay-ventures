"""Assemble the public site for Cloudflare Pages, and its host config.

Cloudflare Pages runs this on every push (build command
`python3 tools/hosting/build.py`, output directory `dist`). It:

  1. Regenerates the portfolio from content/portfolio/*.json
     (tools/portfolio/build.py), so a save in /editor/ is on the site from
     the very next deploy, before the GitHub workflow commits the pages.
  2. Copies only what visitors should get into dist/: the pages, assets,
     logos, the thesis pages and the editor. Never content/ (company data),
     tools/, .github, .claude, CLAUDE.md, CNAME or .nojekyll.
  3. Writes, from one neutral list (tools/hosting/redirects.json) and the
     pages it copied:
       dist/_redirects   the redirects (Cloudflare Pages)
       dist/_headers     caching, security headers, noindex for the editor
                         and for *.pages.dev addresses
       dist/sitemap.xml  every public page with its real last-modified date
                         (a thesis: when its text last changed; any other
                         page: its last commit)
  4. Checks every local link, image, stylesheet and script in the pages
     resolves to a file in dist/, and stops the build if one doesn't.

Another host only needs its own writer here (the Group site's version also
writes .htaccess for Apache). Standard library only:

    python3 tools/hosting/build.py            # into dist/
"""
import datetime as dt
import io
import json
import os
import re
import shutil
import subprocess
import sys

SITE = "https://matchplayventures.com"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DIST = os.path.join(ROOT, "dist")

PUBLISH_DIRS = ["assets", "capital-partners", "editor", "logo", "portco-logos", "portfolio"]
PUBLISH_FILES = ["index.html", "404.html", "favicon.ico", "apple-touch-icon.png",
                 "site.webmanifest", "robots.txt", "llms.txt"]
SKIP = (".DS_Store",)
NOT_IN_SITEMAP = ("editor/", "404.html")      # tools for the team, and the error page


def rel(*parts):
    return os.path.join(ROOT, *parts)


# ---- 1. the portfolio -------------------------------------------------------
def portfolio():
    subprocess.check_call([sys.executable, rel("tools", "portfolio", "build.py")], cwd=ROOT)


# ---- 2. dist/ ---------------------------------------------------------------
def assemble():
    if os.path.isdir(DIST):
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    for name in PUBLISH_FILES:
        shutil.copy2(rel(name), os.path.join(DIST, name))
    for d in PUBLISH_DIRS:
        shutil.copytree(rel(d), os.path.join(DIST, d), ignore=shutil.ignore_patterns(*SKIP))


def pages():
    """Every HTML page in dist/, as paths relative to it."""
    out = []
    for base, _, files in os.walk(DIST):
        for f in files:
            if f.endswith(".html"):
                out.append(os.path.relpath(os.path.join(base, f), DIST).replace(os.sep, "/"))
    return sorted(out)


# ---- 3. host config ---------------------------------------------------------
def load_redirects():
    data = json.load(io.open(rel("tools", "hosting", "redirects.json"), encoding="utf-8"))
    out = []
    for r in data["redirects"]:
        src, to = r["from"].strip(), r["to"].strip()
        if not src.startswith("/"):
            raise SystemExit("redirect 'from' must start with /: %s" % src)
        out.append((src, to))
    return out


def cf_redirects(redirects):
    lines = ["# Generated by tools/hosting/build.py from tools/hosting/redirects.json. Do not edit here."]
    for src, to in redirects:
        lines.append("%s %s 301" % (src, to))
        if not src.endswith("/*"):
            lines.append("%s/ %s 301" % (src, to))
    return "\n".join(lines) + "\n"


def cf_headers():
    # Only images get a long cache: pages, CSS and JS (assets/fx.css and
    # friends) keep their names when they change, so they keep Cloudflare's
    # default of checking for a newer copy each time. Rules must not overlap
    # on one header, or Cloudflare joins the values.
    return "\n".join([
        "# Generated by tools/hosting/build.py. Do not edit here.",
        "/*",
        "  X-Content-Type-Options: nosniff",
        "  Referrer-Policy: strict-origin-when-cross-origin",
        "  X-Frame-Options: SAMEORIGIN",
        "/editor/*",
        "  X-Robots-Tag: noindex, nofollow",
        "/portco-logos/*",
        "  Cache-Control: public, max-age=2592000",
        "/logo/*",
        "  Cache-Control: public, max-age=2592000",
        "/assets/og/*",
        "  Cache-Control: public, max-age=86400",
        "/assets/founders/*",
        "  Cache-Control: public, max-age=2592000",
        "/assets/team/*",
        "  Cache-Control: public, max-age=2592000",
        "# The *.pages.dev addresses are previews: keep them out of search.",
        "https://:project.pages.dev/*",
        "  X-Robots-Tag: noindex",
        "https://:version.:project.pages.dev/*",
        "  X-Robots-Tag: noindex",
        "",
    ])


def git(*args):
    try:
        return subprocess.check_output(["git"] + list(args), cwd=ROOT, stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return None


def last_modified(page, old):
    """The page's last-modified date: its last commit (today if this build
    changed it, e.g. a new editor save the workflow has not committed yet).
    Without full git history (a shallow clone) the date the repo's own
    sitemap.xml gives it (the GitHub workflow, which has the full history,
    commits this build's sitemap there), else today."""
    today = dt.date.today().isoformat()
    if git("status", "--porcelain", "--", page):                # built, not committed yet
        return today
    if git("rev-parse", "--is-shallow-repository") == "false":   # full history
        return git("log", "-1", "--format=%cs", "--", page) or today
    return old or today


def thesis_dates():
    """Thesis web address -> the date its text last changed (the editor
    sets dateModified on every save; the page's structured data uses it too)."""
    out = {}
    folder = rel("content", "portfolio")
    for name in os.listdir(folder):
        if not name.endswith(".json"):
            continue
        c = json.load(io.open(os.path.join(folder, name), encoding="utf-8"))
        a = c.get("article")
        if a and not a.get("hidden") and not c.get("hidden"):
            out["portfolio/%s/index.html" % a["slug"]] = (a.get("dateModified") or a["datePublished"])[:10]
    return out


def sitemap(page_list):
    theses = thesis_dates()
    old = {}
    if os.path.exists(rel("sitemap.xml")):
        xml = io.open(rel("sitemap.xml"), encoding="utf-8").read()
        for loc, mod in re.findall(r"<loc>([^<]+)</loc>\s*<lastmod>([^<]+)</lastmod>", xml):
            old[loc] = mod
    entries = []
    for p in page_list:
        if not p.endswith("index.html") or p.startswith(NOT_IN_SITEMAP):
            continue
        url = SITE + "/" + p[:-len("index.html")]
        entries.append((url, theses.get(p) or last_modified(p, old.get(url))))
    # the homepage first, then the rest in order
    entries.sort(key=lambda e: (e[0] != SITE + "/", e[0]))
    body = "".join("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n  </url>\n" % e for e in entries)
    return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "</urlset>\n", len(entries)


# ---- 4. link check ----------------------------------------------------------
REF = re.compile(r'\b(?:href|src)="([^"]+)"')


def check_links(page_list):
    missing = []
    for p in page_list:
        html = io.open(os.path.join(DIST, p), encoding="utf-8").read()
        html = re.sub(r"<script[^>]*>[\s\S]*?</script>", "", html)   # links built in JS are checked by hand
        for ref in REF.findall(html):
            if re.match(r"^(https?:|mailto:|tel:|data:|#|javascript:)", ref) or "%(" in ref:
                continue
            path = ref.split("#")[0].split("?")[0]
            if not path:
                continue
            base = "" if path.startswith("/") else os.path.dirname(p)
            target = os.path.normpath(os.path.join(DIST, base, path.lstrip("/")))
            if path.endswith("/") or os.path.isdir(target):
                target = os.path.join(target, "index.html")
            if not os.path.exists(target):
                missing.append("%s -> %s" % (p, ref))
    if missing:
        raise SystemExit("Broken local links in dist/:\n  " + "\n  ".join(missing))


def build():
    redirects = load_redirects()
    portfolio()
    assemble()
    page_list = pages()
    io.open(os.path.join(DIST, "_redirects"), "w", encoding="utf-8").write(cf_redirects(redirects))
    io.open(os.path.join(DIST, "_headers"), "w", encoding="utf-8").write(cf_headers())
    xml, n = sitemap(page_list)
    io.open(os.path.join(DIST, "sitemap.xml"), "w", encoding="utf-8").write(xml)
    check_links(page_list)
    files = sum(len(f) for _, _, f in os.walk(DIST))
    print("dist/: %d files, %d pages in the sitemap, %d redirects" % (files, n, len(redirects)))


if __name__ == "__main__":
    build()
